from fastapi import APIRouter, HTTPException
from app.models.schemas import ChatMessage, ChatResponse, ConversationHistory, ConversationMessages
import uuid
from datetime import datetime
from typing import Dict, List

router = APIRouter()

# Mock database for conversations
conversations_db: Dict[str, List] = {}
user_conversations: Dict[str, List] = {}

def mock_web_search(query: str, max_results: int = 5) -> List[Dict]:
    """Mock web search results"""
    return [
        {
            "title": f"Search Result {i+1} for '{query}'",
            "snippet": f"This is a mock search result snippet for query '{query}'. It contains relevant information about the topic.",
            "link": f"https://example{i+1}.com/search-result-{i+1}"
        }
        for i in range(min(max_results, 3))
    ]

def mock_ai_response(message: str, search_results: List[Dict]) -> str:
    """Mock AI response generation"""
    if search_results:
        return f"Based on my search, here's what I found about '{message}': " \
               f"The search results indicate several key points. " \
               f"I found {len(search_results)} relevant sources that provide information on this topic. " \
               f"Would you like me to elaborate on any specific aspect?"
    else:
        return f"I understand you're asking about '{message}'. " \
               f"This is a mock response from the AI assistant. " \
               f"In a real implementation, this would be generated by an AI model like GPT or Claude."

@router.post("/message", response_model=ChatResponse)
async def chat_message(chat_data: ChatMessage):
    """Process chat message with optional web search"""
    try:
        # Generate conversation ID if not provided
        conversation_id = chat_data.conversation_id or str(uuid.uuid4())
        
        # Perform web search if enabled
        search_results = []
        if chat_data.search_enabled:
            search_results = mock_web_search(
                chat_data.message, 
                chat_data.max_search_results
            )
        
        # Generate AI response
        ai_response = mock_ai_response(chat_data.message, search_results)
        
        # Store conversation
        if conversation_id not in conversations_db:
            conversations_db[conversation_id] = []
        
        # Add user message
        conversations_db[conversation_id].append({
            "role": "user",
            "content": chat_data.message,
            "timestamp": datetime.now().isoformat()
        })
        
        # Add assistant message
        conversations_db[conversation_id].append({
            "role": "assistant",
            "content": ai_response,
            "timestamp": datetime.now().isoformat(),
            "search_results": search_results
        })
        
        # Update user conversations list
        if chat_data.user_id not in user_conversations:
            user_conversations[chat_data.user_id] = []
        
        # Check if conversation already exists in user's list
        existing_conv = next(
            (conv for conv in user_conversations[chat_data.user_id] 
             if conv['id'] == conversation_id), 
            None
        )
        
        if not existing_conv:
            user_conversations[chat_data.user_id].append({
                'id': conversation_id,
                'title': chat_data.message[:50] + "..." if len(chat_data.message) > 50 else chat_data.message,
                'timestamp': datetime.now().isoformat(),
                'message_count': 2
            })
        else:
            existing_conv['message_count'] += 2
            existing_conv['timestamp'] = datetime.now().isoformat()
        
        return ChatResponse(
            success=True,
            response=ai_response,
            conversation_id=conversation_id,
            search_results=search_results
        )
        
    except Exception as e:
        raise HTTPException(status_code=500, detail=f"Chat processing failed: {str(e)}")

@router.get("/history/{user_id}", response_model=ConversationHistory)
async def get_chat_history(user_id: str):
    """Get user's chat history"""
    try:
        user_convs = user_conversations.get(user_id, [])
        return ConversationHistory(
            success=True,
            conversations=user_convs
        )
    except Exception as e:
        raise HTTPException(status_code=500, detail=f"Failed to load chat history: {str(e)}")

@router.get("/conversation/{conversation_id}", response_model=ConversationMessages)
async def get_conversation_messages(conversation_id: str, user_id: str):
    """Get messages for a specific conversation"""
    try:
        messages = conversations_db.get(conversation_id, [])
        return ConversationMessages(
            success=True,
            messages=messages
        )
    except Exception as e:
        raise HTTPException(status_code=500, detail=f"Failed to load conversation: {str(e)}")

@router.delete("/conversation/{conversation_id}")
async def delete_conversation(conversation_id: str, user_id: str):
    """Delete a conversation"""
    try:
        # Remove from conversations database
        if conversation_id in conversations_db:
            del conversations_db[conversation_id]
        
        # Remove from user's conversation list
        if user_id in user_conversations:
            user_conversations[user_id] = [
                conv for conv in user_conversations[user_id] 
                if conv['id'] != conversation_id
            ]
        
        return {"success": True, "message": "Conversation deleted successfully"}
        
    except Exception as e:
        raise HTTPException(status_code=500, detail=f"Failed to delete conversation: {str(e)}")

@router.post("/search/web")
async def web_search(search_data: dict):
    """Perform web search"""
    try:
        query = search_data.get("query", "")
        max_results = search_data.get("max_results", 5)
        
        results = mock_web_search(query, max_results)
        
        return {
            "success": True,
            "results": results,
            "query": query
        }
        
    except Exception as e:
        raise HTTPException(status_code=500, detail=f"Search failed: {str(e)}")